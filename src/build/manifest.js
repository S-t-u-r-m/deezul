/**
 * manifest.js — the module list, derived from src/ instead of typed out.
 *
 * Registering a component was pure bookkeeping: `{ ref: 'list-block', src:
 * 'components/ListBlock.js' }` says nothing the file's own path does not already say,
 * and forgetting it produced no error -- the tag rendered as an inert unknown element
 * and nothing mentioned it.
 *
 * The registry still needs a manifest at runtime, because that is how it knows what to
 * dynamic-import and keeps loading lazy. It just does not need a person to write one.
 * deezul-dev serves this and deezul-build writes it, both from the same walk, so the
 * two can never disagree.
 *
 * modules.config.js stays for everything convention cannot express: data stores,
 * explicit `path` entries, inline definitions, and deliberate ref overrides. An app
 * combines them:
 *
 *     import generated from './compiled/modules.generated.js';
 *     import modules from './modules.config.js';
 *     Deezul.init({ modules: [...generated, ...modules] });
 *
 * Later entries win, so naming a ref in modules.config.js overrides the convention.
 */

import { readdir, readFile } from 'fs/promises';
import { join, relative } from 'path';
import { isComponentSource } from '../compiler/library/scriptParser.js';
import { refFromSource, COMPILED_DIR } from '../runtime/modulePaths.js';

/** The generated file's name, inside the compiled directory. */
export const MANIFEST_NAME = 'modules.generated.js';

/** Where it is served from and written to. */
export const MANIFEST_URL = `/${COMPILED_DIR}/${MANIFEST_NAME}`;

const IGNORED = new Set(['node_modules', '.git', 'dist', COMPILED_DIR]);

async function walkJs(dir, base = dir, out = []) {
    let entries;
    try { entries = await readdir(dir, { withFileTypes: true }); } catch { return out; }
    for (const entry of entries) {
        if (entry.name.startsWith('.') || IGNORED.has(entry.name)) continue;
        const full = join(dir, entry.name);
        if (entry.isDirectory()) await walkJs(full, base, out);
        else if (entry.name.endsWith('.js')) out.push(relative(base, full));
    }
    return out;
}

/**
 * Walk src/ and derive one entry per component.
 *
 * @param {string} srcDir
 * @returns {Promise<{modules: Array<{ref: string, src: string}>, warnings: string[]}>}
 */
export async function buildManifest(srcDir) {
    const files = (await walkJs(srcDir)).sort();
    const modules = [];
    const warnings = [];
    const seen = new Map();

    for (const file of files) {
        const source = await readFile(join(srcDir, file), 'utf8');
        if (!isComponentSource(source)) continue;          // a helper module, not a component

        const posix = file.split('\\').join('/');
        const ref = refFromSource(posix);

        if (!ref) {
            warnings.push(
                `${posix}: a component's ref becomes a custom element name, which must contain a ` +
                `hyphen. Rename the file (TodoList.js) or register it by hand in modules.config.js.`,
            );
            continue;
        }
        if (seen.has(ref)) {
            warnings.push(
                `${posix}: ref '${ref}' is already taken by ${seen.get(ref)}. A ref is a name, not ` +
                `a location, so two files cannot share one. Rename one, or register it by hand.`,
            );
            continue;
        }

        seen.set(ref, posix);
        modules.push({ ref, src: posix });
    }

    return { modules, warnings };
}

/** The generated module's source. Plain data: no imports, nothing to resolve. */
export function manifestSource(modules) {
    const lines = [
        '// Generated by deezul from the component files under src/. Do not edit.',
        '// Add data stores, explicit paths and ref overrides in modules.config.js instead.',
        'export default [',
        ...modules.map((m) => `    { ref: ${JSON.stringify(m.ref)}, src: ${JSON.stringify(m.src)} },`),
        '];',
        '',
    ];
    return lines.join('\n');
}
